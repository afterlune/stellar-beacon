// ReviewContentDigest is the stable, non-reversible identity of a generated
// review candidate. It is used to bind an approval to the exact text that was
// shown to the operator without persisting another copy of the content.
func ReviewContentDigest(content string) string {
	digest := sha256.Sum256([]byte(strings.TrimSpace(content)))
	return hex.EncodeToString(digest[:])
}

