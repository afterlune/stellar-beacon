// AIJobRepository is a durable queue contract. Claim must be lease-based and
// implementations must make IdempotencyKey unique at the persistence layer.
type AIJobRepository interface {
	Enqueue(context.Context, AIJob) error
	Claim(context.Context, string, time.Time, time.Duration) (AIJob, bool, error)
	Complete(context.Context, string, string, AIJobResult) error
	Retry(context.Context, string, string, time.Time, string) error
	DeadLetter(context.Context, string, string, string) error
}

// AIJobKindClaimer is an optional refinement implemented by the durable
// PostgreSQL queue. It prevents workers for different capabilities from
// stealing and dead-lettering one another's jobs while keeping the basic
// queue contract usable by small in-memory test fakes.
type AIJobKindClaimer interface {
	ClaimKind(context.Context, string, string, time.Time, time.Duration) (AIJob, bool, error)
}

func ClaimAIJob(ctx context.Context, jobs AIJobRepository, workerID, kind string, now time.Time, lease time.Duration) (AIJob, bool, error) {
	if typed, ok := jobs.(AIJobKindClaimer); ok {
		return typed.ClaimKind(ctx, workerID, kind, now, lease)
	}
	return jobs.Claim(ctx, workerID, now, lease)
}

