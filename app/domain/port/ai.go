type ReviewActionType string

const (
	ReviewActionCreated           ReviewActionType = "created"
	ReviewActionAccepted          ReviewActionType = "accepted"
	ReviewActionPartiallyAccepted ReviewActionType = "partially_accepted"
	ReviewActionRejected          ReviewActionType = "rejected"
	ReviewActionRegenerated       ReviewActionType = "regenerated"
	ReviewActionExpired           ReviewActionType = "expired"
	ReviewActionPublished         ReviewActionType = "published"
	ReviewActionPublishFailed     ReviewActionType = "publish_failed"
)

func NormalizeReviewAction(value string) (ReviewActionType, error) {
	action := ReviewActionType(strings.ToLower(strings.TrimSpace(value)))
	switch action {
	case ReviewActionCreated,
		ReviewActionAccepted,
		ReviewActionPartiallyAccepted,
		ReviewActionRejected,
		ReviewActionRegenerated,
		ReviewActionExpired,
		ReviewActionPublished,
		ReviewActionPublishFailed:
		return action, nil
	default:
		return "", errors.New("review action is invalid")
	}
}

type ReviewPublishStatus string

const (
	ReviewPublishNotAttempted ReviewPublishStatus = "not_attempted"
	ReviewPublishProcessing   ReviewPublishStatus = "processing"
	ReviewPublishSucceeded    ReviewPublishStatus = "succeeded"
	ReviewPublishSkipped      ReviewPublishStatus = "skipped"
	ReviewPublishFailed       ReviewPublishStatus = "failed"
)

func NormalizeReviewPublishStatus(value string) (ReviewPublishStatus, error) {
	status := ReviewPublishStatus(strings.ToLower(strings.TrimSpace(value)))
	switch status {
	case ReviewPublishNotAttempted, ReviewPublishProcessing, ReviewPublishSucceeded, ReviewPublishSkipped, ReviewPublishFailed:
		return status, nil
	default:
		return "", errors.New("review publish status is invalid")
	}
}

