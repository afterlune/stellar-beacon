const PublicArticleStatus = 1

// IsPublicArticle is the single visibility rule shared by lifecycle jobs,
// backfills, projectors, writers, and public search adapters. Callers must
// provide the current persisted status when it is available; event payloads
// are only hints and must not override this rule.
func IsPublicArticle(status, isDelete int) bool {
	return status == PublicArticleStatus && isDelete == 0
}

// ArticleChunkDocument is the provider-neutral schema for one searchable
// article chunk. It intentionally contains source/article metadata so later
// retrieval can return provenance without consulting PostgreSQL for every hit.
// Text cleaning and chunk boundary calculation belong to the indexing worker,
// not to this data contract.
type ArticleChunkDocument struct {
	ID              string    `json:"id"`
	ArticleID       int       `json:"articleId"`
	ArticleTitle    string    `json:"articleTitle"`
	Text            string    `json:"text"`
	Category        string    `json:"category"`
	Tags            []string  `json:"tags"`
	ArticleURL      string    `json:"articleUrl"`
	PublishedAt     time.Time `json:"publishedAt"`
	PublishedAtUnix int64     `json:"publishedAtUnix"`
	ChunkIndex      int       `json:"chunkIndex"`
	Status          int       `json:"status"`
	IsDelete        int       `json:"isDelete"`
}

func (d ArticleChunkDocument) IsPublic() bool {
	return IsPublicArticle(d.Status, d.IsDelete)
}

// IndexedArticleChunk is the complete write contract for the versioned
// article_chunks index. Keeping the vector metadata beside the source
// document prevents an adapter from guessing which model contract produced a
// vector.
type IndexedArticleChunk struct {
	Document           ArticleChunkDocument
	Embedding          []float32
	EmbeddingModel     string
	EmbeddingVersion   string
	EmbeddingDimension int
}

// ArticleChunkIndex owns the article_chunks projection. DeleteArticle is
// deliberately article-scoped: a hard-deleted article no longer provides its
// old chunk count, so deleting by a guessed list of chunk IDs would leave
// stale searchable documents behind.
type ArticleChunkIndex interface {
	UpsertChunks(context.Context, []IndexedArticleChunk) error
	DeleteArticle(context.Context, int) error
}

